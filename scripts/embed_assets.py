#!/usr/bin/env python3
"""Turns web/page.html and assets/icon0.png into src/app_assets.c."""
# SPDX-License-Identifier: GPL-3.0-or-later
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def array(data):
    lines = []
    for start in range(0, len(data), 24):
        lines.append(",".join(str(value) for value in data[start:start + 24]) + ",")
    return "\n".join(lines)


def main():
    page = (ROOT / "web/page.html").read_bytes()
    icon = (ROOT / "assets/icon0.png").read_bytes()
    text = ("/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
            "/* Generated by scripts/embed_assets.py from web/page.html and assets/icon0.png. */\n"
            '#include "http_server.h"\n\n'
            f"const char app_page[] = {{\n{array(page)}\n0}};\n"
            f"const unsigned char app_icon[] = {{\n{array(icon)}\n}};\n"
            f"const unsigned int app_icon_length = {len(icon)};\n")
    target = ROOT / "src/app_assets.c"
    if not target.exists() or target.read_text() != text:
        target.write_text(text)


if __name__ == "__main__":
    main()
